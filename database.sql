CREATE DATABASE IF NOT EXISTS db_ukk2 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_ukk2;

CREATE TABLE IF NOT EXISTS `user` (
  id_user INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  level ENUM('admin','petugas','peminjam') NOT NULL,
  dibuat_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS kategori (
  id_kategori INT AUTO_INCREMENT PRIMARY KEY,
  nama_kategori VARCHAR(100) NOT NULL UNIQUE,
  keterangan TEXT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS alat (
  id_alat INT AUTO_INCREMENT PRIMARY KEY,
  nama_alat VARCHAR(120) NOT NULL,
  id_kategori INT NOT NULL,
  jumlah INT NOT NULL DEFAULT 0,
  kondisi VARCHAR(40) NOT NULL DEFAULT 'Baik',
  keterangan TEXT NULL,
  CONSTRAINT fk_alat_kategori FOREIGN KEY (id_kategori) REFERENCES kategori(id_kategori)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS peminjaman (
  id_peminjaman INT AUTO_INCREMENT PRIMARY KEY,
  id_user INT NOT NULL,
  id_alat INT NOT NULL,
  tanggal_pinjam DATE NOT NULL,
  tanggal_kembali DATE NULL,
  jumlah INT NOT NULL,
  status ENUM('Dipinjam','Dikembalikan') NOT NULL DEFAULT 'Dipinjam',
  keterangan TEXT NULL,
  dibuat_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pinjam_user FOREIGN KEY (id_user) REFERENCES `user`(id_user)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_pinjam_alat FOREIGN KEY (id_alat) REFERENCES alat(id_alat)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS log_aktivitas (
  id_log INT AUTO_INCREMENT PRIMARY KEY,
  id_user INT NULL,
  aktivitas VARCHAR(255) NOT NULL,
  waktu DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_log_user FOREIGN KEY (id_user) REFERENCES `user`(id_user)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;
